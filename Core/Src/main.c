/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_DMA_Init();
  MX_I2C1_Init();
  MX_USART1_UART_Init();
  MX_TIM2_Init();
  /* USER CODE BEGIN 2 */

  printf("\r\n=== STM32F103 Robot: MPU6050 Test Start ===\r\n");

  // Ініціалізуємо драйвер, передаючи I2C1 та TIM2
  MPU6050_Init_Async(&hmpu1, &hi2c1, &htim2);

  // Крутимо автомат станів, поки датчик не перейде в режим READY
  printf("Initializing MPU6050...\r\n");
  while (hmpu1.state != MPU_STATE_READY && hmpu1.state != MPU_STATE_ERROR) {
      MPU6050_Process_State(&hmpu1);
  }

  if (hmpu1.state == MPU_STATE_READY) {
      printf("MPU6050 Initialized Successfully!\r\n");
  } else {
      printf("MPU6050 Initialization ERROR!\r\n");
  }

  printf("MPU6050 Initialized. Calibrating Gyro... DO NOT MOVE!\r\n");
  MPU6050_Calibrate_Gyro_Z(&hmpu1, 500); // Беремо 500 точок для точного прорахунку нуля
  printf("Calibration Done! Offset Z: %ld\r\n", hmpu1.gyro_z_offset);

  mpu_timer = HAL_GetTick();

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {

	// Обов'язково викликаємо Process_State на кожній ітерації суперциклу
	MPU6050_Process_State(&hmpu1);

	// Неблокуючий запуск читання кожні 20 мс (Частота 50 Гц)
	if (HAL_GetTick() - mpu_timer >= 20) {
	    mpu_timer = HAL_GetTick();

	    if (hmpu1.state == MPU_STATE_READY) {
	        hmpu1.state = MPU_STATE_READING_DATA; // Переводимо в стан читання
	    }
	}

    static MPU_State_t prev_state = MPU_STATE_UNINIT;
    if (hmpu1.state == MPU_STATE_READY && prev_state == MPU_STATE_READING_DATA) {
        // Розраховуємо кут на основі точного часу з TIM2
        MPU6050_Update_Angle(&hmpu1);

        // Виводимо швидкість повороту та поточний кут машинки в градусах
        printf("SPEED_Z: %.2f deg/s | ANGLE_Z: %.2f deg\r\n",
               hmpu1.gyro_z_dps,
               hmpu1.angle_z);
    }
    prev_state = hmpu1.state;


	/* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

